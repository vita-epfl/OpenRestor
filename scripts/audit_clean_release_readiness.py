#!/usr/bin/env python3
"""Audit a Clean manifest/profile set before any public release.

This is an offline, fail-closed gate.  It does not copy or upload audio and it
does not infer rights from a dataset-level licence or an acoustic score.  A
``GO`` means only that the supplied metadata/profile inputs satisfy the
mechanical checks; legal approval and scientific review remain separate gates.
"""

from __future__ import annotations

import argparse
import collections
import hashlib
import json
from pathlib import Path


PROFILES = ("public_research", "public_commercial", "internal_research", "blocked")
PUBLIC_PROFILES = {"public_research", "public_commercial"}
REQUIRED_RIGHTS = ("license_url", "attribution", "evidence_url", "evidence_date")
PERMISSION_FIELDS = ("allow_redistribution", "allow_derivatives")


def read_jsonl(path: Path):
    with path.open(encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, 1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as error:
                raise ValueError(f"invalid JSON at {path}:{line_number}") from error
            if not isinstance(row, dict):
                raise ValueError(f"JSONL row is not an object at {path}:{line_number}")
            yield row


def _key(row: dict) -> str:
    dataset, source_id = str(row.get("dataset") or ""), str(row.get("source_id") or "")
    if not dataset or not source_id:
        raise ValueError("manifest row requires dataset and source_id")
    return f"{dataset}:{source_id}"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _load_profile(path: Path, profile: str) -> dict[str, dict]:
    rows = {}
    for row in read_jsonl(path):
        key = _key(row)
        if key in rows:
            raise ValueError(f"duplicate source in {profile}: {key}")
        rows[key] = row
    return rows


def _base_payload(row: dict) -> dict:
    """Strip only fields generated by the profile exporter."""
    generated = {"rights_profile", "rights_family", "blocked_reason"}
    return {key: value for key, value in row.items() if key not in generated}


def audit(manifest_path: Path, profiles_dir: Path, *, split_report: Path | None = None,
          require_technical: bool = True, require_lossless: bool = True,
          verify_local_checksums: bool = False) -> dict:
    manifest = {}
    for row in read_jsonl(manifest_path):
        key = _key(row)
        if key in manifest:
            raise ValueError(f"duplicate source in manifest: {key}")
        manifest[key] = row
    profile_rows = {}
    for profile in PROFILES:
        path = profiles_dir / f"{profile}.jsonl"
        if not path.is_file():
            raise FileNotFoundError(f"missing profile: {path}")
        profile_rows[profile] = _load_profile(path, profile)

    errors: list[dict] = []
    warnings: list[dict] = []
    memberships: dict[str, set[str]] = collections.defaultdict(set)
    for profile, rows in profile_rows.items():
        for key, row in rows.items():
            if key not in manifest:
                errors.append({"code": "profile_source_absent_from_manifest", "profile": profile, "source_key": key})
            elif _base_payload(row) != _base_payload(manifest[key]):
                errors.append({"code": "profile_row_differs_from_manifest", "profile": profile,
                               "source_key": key})
            memberships[key].add(profile)
            if row.get("rights_profile") != profile:
                errors.append({"code": "profile_label_mismatch", "profile": profile, "source_key": key,
                               "rights_profile": row.get("rights_profile")})
    # The public views overlap intentionally: commercial eligibility implies
    # noncommercial research eligibility. Blocked and internal remain fallback
    # categories, never companions to a public view.
    base_profiles = {"public_research", "internal_research", "blocked"}
    missing_profiles = sorted(set(manifest) - {key for key, profiles in memberships.items()
                                               if profiles & base_profiles})
    for key in missing_profiles:
        errors.append({"code": "manifest_source_missing_from_profiles", "source_key": key})

    for key, profiles in sorted(memberships.items()):
        if "public_commercial" in profiles and "public_research" not in profiles:
            errors.append({"code": "commercial_without_research_profile", "source_key": key})
        if len(profiles & base_profiles) > 1:
            errors.append({"code": "source_in_multiple_profiles", "source_key": key,
                           "profiles": sorted(profiles)})
    for key in sorted(set(profile_rows["public_commercial"]) & set(profile_rows["public_research"])):
        research = profile_rows["public_research"][key]
        commercial = profile_rows["public_commercial"][key]
        if _base_payload(research) != _base_payload(commercial):
            errors.append({"code": "public_profile_row_mismatch", "source_key": key})

    public_rows = [(profile, key, row) for profile in PUBLIC_PROFILES
                   for key, row in profile_rows[profile].items()]
    for profile, key, row in public_rows:
        rights = row.get("rights")
        if not isinstance(rights, dict):
            errors.append({"code": "missing_rights", "profile": profile, "source_key": key})
            continue
        if rights.get("provenance_approved") is not True:
            errors.append({"code": "provenance_not_approved", "profile": profile, "source_key": key})
        if rights.get("redistribution_approved") is not True:
            errors.append({"code": "redistribution_not_approved", "profile": profile, "source_key": key})
        if rights.get("review_status") != "approved":
            errors.append({"code": "rights_review_not_approved", "profile": profile, "source_key": key,
                           "review_status": rights.get("review_status")})
        for field in REQUIRED_RIGHTS:
            if rights.get(field) in (None, ""):
                errors.append({"code": f"missing_{field}", "profile": profile, "source_key": key})
        for field in PERMISSION_FIELDS:
            if rights.get(field) is not True:
                errors.append({"code": f"missing_{field}", "profile": profile, "source_key": key})
        if profile == "public_commercial" and rights.get("allow_commercial") is not True:
            errors.append({"code": "commercial_use_not_allowed", "profile": profile, "source_key": key})
        if require_technical and row.get("technical_candidate") is not True:
            errors.append({"code": "technical_candidate_false", "profile": profile, "source_key": key})
        if require_lossless and row.get("lossless_status") != "clean_lossless":
            errors.append({"code": "lossless_not_verified", "profile": profile, "source_key": key,
                           "lossless_status": row.get("lossless_status")})
        if not row.get("audio_path"):
            errors.append({"code": "audio_path_missing", "profile": profile, "source_key": key})
        elif verify_local_checksums:
            path = Path(str(row["audio_path"]))
            expected = str(row.get("source_sha256") or "").lower()
            if not path.is_file():
                errors.append({"code": "audio_file_missing", "profile": profile, "source_key": key,
                               "audio_path": str(path)})
            elif not expected:
                errors.append({"code": "source_sha256_missing", "profile": profile, "source_key": key})
            elif _sha256(path) != expected:
                errors.append({"code": "source_sha256_mismatch", "profile": profile, "source_key": key})
    if split_report:
        split = json.loads(split_report.read_text(encoding="utf-8"))
        if split.get("split_disjoint") is not True:
            errors.append({"code": "split_not_disjoint"})
        if split.get("rights_not_inferred") is not True:
            errors.append({"code": "split_report_infers_rights"})
    unique_public_keys = set(profile_rows["public_research"]) | set(profile_rows["public_commercial"])
    if not unique_public_keys:
        warnings.append({"code": "no_public_sources", "message": "No approved public profile is non-empty."})

    counts = {profile: len(rows) for profile, rows in profile_rows.items()}
    error_counts = collections.Counter(item["code"] for item in errors)
    return {
        "schema_version": "clean-release-readiness-v2",
        "manifest": str(manifest_path),
        "manifest_sources": len(manifest),
        "profile_sources": counts,
        "profile_partition_complete": not missing_profiles and not any(
            item["code"] in {"source_in_multiple_profiles", "commercial_without_research_profile"}
            for item in errors),
        "public_sources": len(unique_public_keys),
        "public_profile_overlap": len(set(profile_rows["public_research"]) &
                                      set(profile_rows["public_commercial"])),
        "require_technical": require_technical,
        "require_lossless": require_lossless,
        "verify_local_checksums": verify_local_checksums,
        "split_report": str(split_report) if split_report else None,
        "errors": errors,
        "error_counts": dict(sorted(error_counts.items())),
        "warnings": warnings,
        "verdict": "GO" if not errors and unique_public_keys else "NO-GO",
        "audio_copied": False,
        "audio_uploaded": False,
        "rights_inferred": False,
        "note": "Mechanical gate only; not legal approval or scientific quality validation.",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--profiles-dir", type=Path, required=True)
    parser.add_argument("--split-report", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--allow-unverified-lossless", action="store_true")
    parser.add_argument("--skip-technical-gate", action="store_true")
    parser.add_argument("--verify-local-checksums", action="store_true")
    args = parser.parse_args()
    result = audit(args.manifest, args.profiles_dir, split_report=args.split_report,
                   require_technical=not args.skip_technical_gate,
                   require_lossless=not args.allow_unverified_lossless,
                   verify_local_checksums=args.verify_local_checksums)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                         encoding="utf-8")
    print(f"Clean release readiness: {result['verdict']} ({len(result['errors'])} errors)")
    if result["verdict"] != "GO":
        raise SystemExit(2)


if __name__ == "__main__":
    main()
